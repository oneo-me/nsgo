// A package's catalogs are a YAML file per language in its directory,
// named by BCP 47 tags (en.yaml, zh-Hans.yaml), from which the tool
// writes catalog_gen.go, the package's typed function per message
// (i18n_gen.go). The source language's file has every message, and may
// describe it:
//
//	greeting: "Hello, {name}!"
//	filesSelected:
//	  message: "{count, plural, one {# file} other {# files}}"
//	  description: The status bar, while files are selected.
//	  placeholders:
//	    count: {type: int}
//
// A key that is an import path supplies another package's catalog in the
// file's language, under that package's keys:
//
//	github.com/oneo-me/nsgo/base/locales:
//	  sortBy: "Nach {column} sortieren"

// genFile is the file the tool writes into a catalogs' directory.
const genFile = "catalog_gen.go"

// genHeader starts genFile, by which the tool knows a package of catalogs.
const genHeader = "// Code generated by nsgo i18n from the catalogs in this directory. DO NOT EDIT."

// catalog is a package's catalogs.
type catalog struct {
	dir, pkg   string
	importPath string
	source     string
	// app makes the catalog the app's: its languages are those it shows.
	app   bool
	files map[string]*catalogFile // by language
	// keys are the source's, in its order, with the parameters of each.
	keys   []string
	params map[string][]param
}

// catalogFile is one language's file.
type catalogFile struct {
	lang, path string
	keys       []string
	msgs       map[string]*catalogMessage
	supplies   []*supply
}

type catalogMessage struct {
	key, text, desc string
	parts           []msgPart
	line            int
	// placeholders are the source's declared parameters, in order.
	placeholders []param
}

// param is a message's parameter and its Go type: string, int, float64
// or any.
type param struct {
	name, typ string
	line      int
}

// supply is a section of a file supplying another package's catalog.
type supply struct {
	importPath string
	line       int
	keys       []string
	msgs       map[string]*catalogMessage
	target     *catalog
}

// diag is a problem in a catalog: an error stops generating, a warning
// does not.
type diag struct {
	path string
	line int
	msg  string
	warn bool
}

func (d diag) String() string {
	at := d.path
	if d.line > 0 {
		at += ":" + strconv.Itoa(d.line)
	}
	return at + ": " + d.msg
}

type diags []diag

func (ds *diags) errorf(path string, line int, format string, args ...any) {
	*ds = append(*ds, diag{path: path, line: line, msg: fmt.Sprintf(format, args...)})
}

func (ds *diags) warnf(path string, line int, format string, args ...any) {
	*ds = append(*ds, diag{path: path, line: line, msg: fmt.Sprintf(format, args...), warn: true})
}

// err returns the errors as one, or nil.
func (ds diags) err() error {
	var lines []string
	for _, d := range ds {
		if !d.warn {
			lines = append(lines, d.String())
		}
	}
	if len(lines) == 0 {
		return nil
	}
	return fmt.Errorf("catalogs have errors\n%s", strings.Join(lines, "\n"))
}

// printWarnings prints the warnings, relative to the working directory.
func (ds diags) printWarnings() {
	for _, d := range ds {
		if d.warn {
			d.path = rel(d.path)
			warn("%s", d)
		}
	}
}

// hasCatalogs reports whether dir holds catalogs.
func hasCatalogs(dir string) bool {
	m, _ := filepath.Glob(filepath.Join(dir, "*.yaml"))
	return len(m) > 0
}

// languages returns the catalog's languages, the source's first.
func (c *catalog) languages() []string {
	langs := []string{c.source}
	for lang := range c.files {
		if lang != c.source {
			langs = append(langs, lang)
		}
	}
	slices.Sort(langs[1:])
	return langs
}

// loadCatalog reads and checks the catalogs in dir, written in source.
func loadCatalog(dir, source string) (*catalog, diags) {
	var ds diags
	c := &catalog{dir: dir, source: source, files: map[string]*catalogFile{}, params: map[string][]param{}}
	c.pkg = catalogPackage(dir)
	paths, _ := filepath.Glob(filepath.Join(dir, "*.yaml"))
	for _, path := range paths {
		lang := strings.TrimSuffix(filepath.Base(path), ".yaml")
		if t, err := language.Parse(lang); err != nil || t.String() != lang || t.IsRoot() {
			want := ""
			if err == nil && !t.IsRoot() {
				want = fmt.Sprintf(" (%s.yaml)", t)
			}
			ds.errorf(path, 0, "not named after a canonical BCP 47 tag%s", want)
			continue
		}
		f := readCatalogFile(path, lang, &ds)
		if f != nil {
			c.files[lang] = f
		}
	}
	src := c.files[source]
	if src == nil {
		ds.errorf(filepath.Join(dir, source+".yaml"), 0, "missing: the source language's catalog, with every message")
		return c, ds
	}
	c.keys = src.keys
	names := map[string]string{}
	for _, key := range src.keys {
		m := src.msgs[key]
		name := exportName(key)
		if other, ok := names[strings.ToLower(name)]; ok {
			ds.errorf(src.path, m.line, "%s and %s make functions of the same name", other, key)
		} else if slices.Contains(reservedNames, name) {
			ds.errorf(src.path, m.line, "%s makes %s, which the package already declares", key, name)
		}
		names[strings.ToLower(name)] = key
		c.params[key] = sourceParams(m, src.path, &ds)
		checkPluralCases(m, source, src.path, &ds)
	}
	for _, f := range c.files {
		if f.lang == source {
			continue
		}
		var missing []string
		for _, key := range src.keys {
			if f.msgs[key] == nil {
				missing = append(missing, key)
			}
		}
		if len(missing) > 0 {
			ds.warnf(f.path, 0, "lacks %d of the source's messages, which say %s's: %s", len(missing), source, strings.Join(missing, ", "))
		}
		for _, key := range f.keys {
			m := f.msgs[key]
			if _, ok := c.params[key]; !ok {
				ds.errorf(f.path, m.line, "%s is not a message of %s.yaml", key, source)
				continue
			}
			checkTranslation(m, c.params[key], f.lang, f.path, &ds)
		}
	}
	return c, ds
}

// readCatalogFile reads one language's file.
func readCatalogFile(path, lang string, ds *diags) *catalogFile {
	data, err := os.ReadFile(path)
	if err != nil {
		ds.errorf(path, 0, "%v", err)
		return nil
	}
	f := &catalogFile{lang: lang, path: path, msgs: map[string]*catalogMessage{}}
	var doc yaml.Node
	if err := yaml.Unmarshal(data, &doc); err != nil {
		ds.errorf(path, 0, "%v", err)
		return nil
	}
	if len(doc.Content) == 0 {
		return f
	}
	root := doc.Content[0]
	if root.Kind != yaml.MappingNode {
		ds.errorf(path, root.Line, "want a mapping of messages")
		return nil
	}
	for i := 0; i+1 < len(root.Content); i += 2 {
		k, v := root.Content[i], root.Content[i+1]
		if strings.ContainsAny(k.Value, "/.") {
			s := &supply{importPath: k.Value, line: k.Line, msgs: map[string]*catalogMessage{}}
			if v.Kind != yaml.MappingNode {
				ds.errorf(path, v.Line, "%s: want a mapping of its messages", k.Value)
				continue
			}
			for j := 0; j+1 < len(v.Content); j += 2 {
				if m := readMessage(v.Content[j], v.Content[j+1], path, ds); m != nil {
					if s.msgs[m.key] != nil {
						ds.errorf(path, m.line, "%s twice", m.key)
						continue
					}
					s.keys = append(s.keys, m.key)
					s.msgs[m.key] = m
				}
			}
			f.supplies = append(f.supplies, s)
			continue
		}
		if m := readMessage(k, v, path, ds); m != nil {
			if f.msgs[m.key] != nil {
				ds.errorf(path, m.line, "%s twice", m.key)
				continue
			}
			f.keys = append(f.keys, m.key)
			f.msgs[m.key] = m
		}
	}
	return f
}

// readMessage reads a key and its message: a string, or a mapping of
// message, description and placeholders.
func readMessage(k, v *yaml.Node, path string, ds *diags) *catalogMessage {
	m := &catalogMessage{key: k.Value, line: k.Line}
	if !validIdent(m.key) || m.key[0] == '_' {
		ds.errorf(path, k.Line, "key %q: want a letter, then letters, digits and _", m.key)
		return nil
	}
	switch v.Kind {
	case yaml.ScalarNode:
		m.text = v.Value
	case yaml.MappingNode:
		found := false
		for i := 0; i+1 < len(v.Content); i += 2 {
			field, value := v.Content[i], v.Content[i+1]
			switch field.Value {
			case "message":
				m.text, found = value.Value, true
			case "description":
				m.desc = value.Value
			case "placeholders":
				if value.Kind != yaml.MappingNode {
					ds.errorf(path, value.Line, "%s: placeholders: want a mapping", m.key)
					continue
				}
				for j := 0; j+1 < len(value.Content); j += 2 {
					name, spec := value.Content[j], value.Content[j+1]
					p := param{name: name.Value, line: name.Line}
					if spec.Kind == yaml.MappingNode {
						for n := 0; n+1 < len(spec.Content); n += 2 {
							if spec.Content[n].Value == "type" {
								p.typ = spec.Content[n+1].Value
							}
						}
					}
					m.placeholders = append(m.placeholders, p)
				}
			default:
				ds.errorf(path, field.Line, "%s: unknown field %s; use message, description or placeholders", m.key, field.Value)
			}
		}
		if !found {
			ds.errorf(path, v.Line, "%s: no message", m.key)
			return nil
		}
	default:
		ds.errorf(path, v.Line, "%s: want a message", m.key)
		return nil
	}
	parts, err := parseMessage(m.text)
	if err != nil {
		ds.errorf(path, m.line, "%s: %v", m.key, err)
		return nil
	}
	m.parts = parts
	return m
}

// placeholderTypes maps ARB's placeholder types to Go's.
var placeholderTypes = map[string]string{
	"String": "string", "int": "int", "double": "float64", "num": "float64", "Object": "any",
}

// sourceParams returns a source message's parameters: its placeholders',
// in order, then the arguments it uses besides, typed by how it uses them.
func sourceParams(m *catalogMessage, path string, ds *diags) []param {
	order, uses := messageArgs(m.parts)
	var params []param
	declared := map[string]bool{}
	for _, p := range m.placeholders {
		if p.typ == "DateTime" {
			ds.errorf(path, p.line, "%s: %s: DateTime placeholders are not supported yet", m.key, p.name)
			continue
		}
		typ := "string"
		if p.typ != "" {
			var ok bool
			if typ, ok = placeholderTypes[p.typ]; !ok {
				ds.errorf(path, p.line, "%s: %s: unknown type %s; use String, int, double, num or Object", m.key, p.name, p.typ)
				continue
			}
		} else {
			typ = inferredType(uses[p.name])
		}
		if _, used := uses[p.name]; !used {
			ds.warnf(path, p.line, "%s: placeholder %s is not in the message", m.key, p.name)
		}
		declared[p.name] = true
		params = append(params, param{name: p.name, typ: typ, line: p.line})
	}
	for _, name := range order {
		if declared[name] {
			continue
		}
		params = append(params, param{name: name, typ: inferredType(uses[name]), line: m.line})
	}
	for _, p := range params {
		checkUse(m, p, uses[p.name], path, ds)
	}
	return params
}

// inferredType is the type of a parameter without one: float64 for a
// percentage, int for another number or a count, else string.
func inferredType(use argUse) string {
	switch {
	case use&usePercent != 0:
		return "float64"
	case use&useNumber != 0:
		return "int"
	}
	return "string"
}

// checkTranslation checks a translation's arguments against the source's
// parameters, and its plural cases against its language's categories.
func checkTranslation(m *catalogMessage, params []param, lang, path string, ds *diags) {
	_, uses := messageArgs(m.parts)
	for name, use := range uses {
		i := slices.IndexFunc(params, func(p param) bool { return p.name == name })
		if i < 0 {
			ds.errorf(path, m.line, "%s: {%s} is not an argument of the source's message", m.key, name)
			continue
		}
		checkUse(m, params[i], use, path, ds)
	}
	checkPluralCases(m, lang, path, ds)
}

// checkUse checks that a message uses a parameter as its type allows.
func checkUse(m *catalogMessage, p param, use argUse, path string, ds *diags) {
	switch {
	case use&useNumber != 0 && use&useSelect != 0:
		ds.errorf(path, m.line, "%s: %s is both counted and selected on", m.key, p.name)
	case use&useNumber != 0 && (p.typ == "string" || p.typ == "any"):
		ds.errorf(path, m.line, "%s: %s is a %s, which a number or plural cannot count", m.key, p.name, p.typ)
	case use&useSelect != 0 && p.typ != "string":
		ds.errorf(path, m.line, "%s: %s is a %s, which select cannot choose by", m.key, p.name, p.typ)
	}
}

// checkPluralCases warns of plural cases lang never says and categories
// it has that a choice lacks.
func checkPluralCases(m *catalogMessage, lang, path string, ds *diags) {
	for _, kind := range []string{"plural", "selectordinal"} {
		has := pluralCategories(lang, kind == "selectordinal")
		for _, keys := range pluralCases(m.parts, kind) {
			for _, k := range keys {
				if !has[k] {
					ds.warnf(path, m.line, "%s: %s has no %s %s case", m.key, lang, k, kind)
				}
			}
			for _, k := range pluralKeys {
				if has[k] && !slices.Contains(keys, k) {
					ds.warnf(path, m.line, "%s: lacks %s's %s case, which says other", m.key, lang, k)
				}
			}
		}
	}
}

// pluralCategories returns the categories lang's plural rules put
// numbers in, found by trying numbers on them once per language and kind:
// every message of every catalog asks. The numbers are as i18n's
// Cardinal and Ordinal see them, written without trailing zeros, but
// the tool reads the rules itself, so it links no engine.
func pluralCategories(lang string, ordinal bool) map[string]bool {
	type kind struct {
		lang    string
		ordinal bool
	}
	if has, ok := pluralCategoryCache.Load(kind{lang, ordinal}); ok {
		return has.(map[string]bool)
	}
	rules, tag := plural.Cardinal, language.Make(lang)
	if ordinal {
		rules = plural.Ordinal
	}
	names := [...]string{plural.Other: "other", plural.Zero: "zero", plural.One: "one", plural.Two: "two", plural.Few: "few", plural.Many: "many"}
	has := map[string]bool{}
	// try tries the number i.f, f having v digits.
	try := func(i, v, f int) { has[names[rules.MatchPlural(tag, i, v, v, f, f)]] = true }
	for n := 0; n <= 1000; n++ {
		try(n, 0, 0)
	}
	for _, n := range []int{1e4, 1e5, 1e6, 1e7, 1e9} {
		try(n, 0, 0)
	}
	if !ordinal {
		// Tenths below 30 and hundredths below 3, those ending in 0
		// tried with fewer digits already.
		for n := 1; n < 300; n++ {
			if n%10 != 0 {
				try(n/10, 1, n%10)
				try(n/100, 2, n%100)
			}
		}
	}
	pluralCategoryCache.Store(kind{lang, ordinal}, has)
	return has
}

var pluralCategoryCache sync.Map

// reservedNames are what a package of catalogs declares besides its
// messages.
var reservedNames = []string{"Source", "Catalog", "Messages", "In", "For", "Translation", "Supply"}

// exportName is the functions' name for a key.
func exportName(key string) string { return strings.ToUpper(key[:1]) + key[1:] }

// catalogPackage is the name of dir's package: as its Go files say, else
// its directory's.
func catalogPackage(dir string) string {
	if name, err := packageName(dir); err == nil {
		return name
	}
	var b strings.Builder
	for _, c := range strings.ToLower(filepath.Base(dir)) {
		if 'a' <= c && c <= 'z' || '0' <= c && c <= '9' && b.Len() > 0 {
			b.WriteRune(c)
		}
	}
	if b.Len() == 0 {
		return "locales"
	}
	return b.String()
}

// generatedCatalog reads what catalog_gen.go in dir says of its catalogs:
// their source language and whether they are the app's. ok is false when
// dir has none the tool wrote.
func generatedCatalog(dir string) (source string, app, ok bool) {
	data, err := os.ReadFile(filepath.Join(dir, genFile))
	if err != nil || !strings.HasPrefix(string(data), genHeader) {
		return "", false, false
	}
	_, rest, found := strings.Cut(string(data), "\nconst Source = ")
	if !found {
		return "", false, false
	}
	line, _, _ := strings.Cut(rest, "\n")
	source, err = strconv.Unquote(strings.TrimSpace(line))
	if err != nil {
		return "", false, false
	}
	return source, strings.Contains(string(data), "\n\ti18n.SetApp(Catalog)\n"), true
}
