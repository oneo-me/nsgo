// Command gen writes kindnames_gen.go: the name of every view, item, event
// and drawing kind, so a log says ItemModal rather than 20. It reads the
// const blocks of the driver's own files, so a kind added there is named
// without a second list to keep.
package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
)

type kind struct {
	typeName string
	first    string
	file     string
	target   string // the name its table takes
}

func main() {
	kinds := []kind{
		{"ItemKind", "ItemCreate", "mount.go", "item"},
		{"EventKind", "EventPress", "events.go", "event"},
		{"DrawKind", "DrawSave", "canvas.go", "draw"},
	}
	var b bytes.Buffer
	b.WriteString("// Code generated by go generate; DO NOT EDIT.\n\npackage driver\n\nimport \"strconv\"\n")
	for _, k := range kinds {
		names, err := constNames(k.file, k.first)
		if err != nil {
			fmt.Fprintf(os.Stderr, "gen: %v\n", err)
			os.Exit(1)
		}
		if len(names) == 0 {
			fmt.Fprintf(os.Stderr, "gen: no %s constants in %s\n", k.first, k.file)
			os.Exit(1)
		}
		table := k.target + "KindNames"
		fmt.Fprintf(&b, "\nvar %s = map[%s]string{\n", table, k.typeName)
		for _, n := range names {
			fmt.Fprintf(&b, "\t%s: %q,\n", n, n)
		}
		b.WriteString("}\n\n")
		fmt.Fprintf(&b, "// String returns the kind's name, as a log or an event prints it.\nfunc (k %s) String() string {\n", k.typeName)
		fmt.Fprintf(&b, "\tif s, ok := %s[k]; ok {\n\t\treturn s\n\t}\n\treturn %q + strconv.Itoa(int(k)) + \")\"\n}\n", table, k.typeName+"(")
	}
	out, err := format.Source(b.Bytes())
	if err != nil {
		fmt.Fprintf(os.Stderr, "gen: %v\n", err)
		os.Exit(1)
	}
	if err := os.WriteFile("kindnames_gen.go", out, 0o644); err != nil {
		fmt.Fprintf(os.Stderr, "gen: %v\n", err)
		os.Exit(1)
	}
}

// constNames returns the names of the const block that starts with first.
func constNames(file, first string) ([]string, error) {
	fset := token.NewFileSet()
	f, err := parser.ParseFile(fset, file, nil, 0)
	if err != nil {
		return nil, err
	}
	for _, d := range f.Decls {
		gd, ok := d.(*ast.GenDecl)
		if !ok || gd.Tok != token.CONST {
			continue
		}
		var names []string
		for _, s := range gd.Specs {
			vs, ok := s.(*ast.ValueSpec)
			if !ok {
				continue
			}
			for _, n := range vs.Names {
				names = append(names, n.Name)
			}
		}
		if len(names) > 0 && names[0] == first {
			return names, nil
		}
	}
	return nil, nil
}
