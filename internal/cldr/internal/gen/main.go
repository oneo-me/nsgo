// Command gen writes tables.go, the data of the Unicode CLDR package cldr
// formats dates with, from a pinned release of cldr-json: go generate
// ./internal/cldr runs it. It reads the npm packages cldr-core,
// cldr-dates-full and cldr-numbers-full, each checked against its
// SHA-256, and keeps the locales of CLDR's modern coverage and their
// parents. A locale keeps only the entries in which it differs from its
// parent, deflated.
package main

import (
	"archive/tar"
	"bytes"
	"compress/flate"
	"compress/gzip"
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"io"
	"log"
	"net/http"
	"os"
	"path/filepath"
	"slices"
	"strings"
)

const version = "48.2.0"

var packages = map[string]string{
	"cldr-core":         "5310e0c7a06c1feb83dc8e54c8584bbe0b9c2ea8320172a18d541986b124585d",
	"cldr-dates-full":   "0256f1cefeca14f7d515be4872dda48fcdd7e75381430f25aafd0143eae5b430",
	"cldr-numbers-full": "2d17a1453c559a62112caeed52e0bcfe3cb8539c99d239ae7b7ed4d0827679d9",
}

func main() {
	log.SetFlags(0)
	log.SetPrefix("gen: ")
	out := flag.String("o", ".", "the directory of package cldr")
	cache := flag.String("cache", "", "a directory holding the packages' tarballs, <name>-<version>.tgz (default: download them)")
	flag.Parse()

	files := map[string][]byte{}
	for name, sum := range packages {
		if err := read(name, sum, *cache, files); err != nil {
			log.Fatal(err)
		}
	}
	var coverage struct {
		Effective map[string]string `json:"effectiveCoverageLevels"`
	}
	decode(files, "cldr-core/coverageLevels.json", &coverage)
	var parents struct {
		Supplemental struct {
			ParentLocales struct {
				ParentLocale map[string]string `json:"parentLocale"`
			} `json:"parentLocales"`
		} `json:"supplemental"`
	}
	decode(files, "cldr-core/supplemental/parentLocales.json", &parents)
	explicit := parents.Supplemental.ParentLocales.ParentLocale
	parentOf := func(loc string) string {
		if p, ok := explicit[loc]; ok {
			if p == "root" {
				return "und"
			}
			return p
		}
		if i := strings.LastIndexByte(loc, '-'); i > 0 {
			return loc[:i]
		}
		if loc == "und" {
			return ""
		}
		return "und"
	}

	keep := map[string]bool{}
	for loc, level := range coverage.Effective {
		if level != "modern" {
			continue
		}
		for l := loc; l != ""; l = parentOf(l) {
			if _, ok := files["cldr-dates-full/main/"+l+"/ca-gregorian.json"]; ok {
				keep[l] = true
			}
		}
	}
	keep["und"] = true
	locales := make([]string, 0, len(keep))
	for l := range keep {
		locales = append(locales, l)
	}
	slices.Sort(locales)

	var digits struct {
		Supplemental struct {
			NumberingSystems map[string]struct {
				Digits string `json:"_digits"`
			} `json:"numberingSystems"`
		} `json:"supplemental"`
	}
	decode(files, "cldr-core/supplemental/numberingSystems.json", &digits)

	resolved := map[string]map[string]string{}
	var resolve func(loc string) map[string]string
	resolve = func(loc string) map[string]string {
		if r, ok := resolved[loc]; ok {
			return r
		}
		r := map[string]string{}
		if p := parentOf(loc); p != "" {
			for k, v := range resolve(p) {
				r[k] = v
			}
		}
		for k, v := range entries(files, loc, digits.Supplemental.NumberingSystems) {
			r[k] = v
		}
		resolved[loc] = r
		return r
	}

	var records []string
	parentIndex := make([]int, len(locales))
	for i, loc := range locales {
		own := resolve(loc)
		var base map[string]string
		parentIndex[i] = -1
		if p := parentOf(loc); p != "" {
			for !keep[p] {
				p = parentOf(p)
			}
			base = resolve(p)
			parentIndex[i], _ = slices.BinarySearch(locales, p)
		}
		keys := make([]string, 0, len(own))
		for k, v := range own {
			if base == nil || base[k] != v {
				keys = append(keys, k)
			}
		}
		slices.Sort(keys)
		var fields []string
		for _, k := range keys {
			fields = append(fields, k+"\x1f"+own[k])
		}
		records = append(records, strings.Join(fields, "\x1e"))
	}
	var packed bytes.Buffer
	w, _ := flate.NewWriter(&packed, flate.BestCompression)
	w.Write([]byte(strings.Join(records, "\x1d")))
	w.Close()

	var rules struct {
		Supplemental struct {
			Sets map[string]map[string]struct {
				At     string `json:"_at"`
				From   string `json:"_from"`
				Before string `json:"_before"`
			} `json:"dayPeriodRuleSet"`
		} `json:"supplemental"`
	}
	decode(files, "cldr-core/supplemental/dayPeriods.json", &rules)
	langs := make([]string, 0, len(rules.Supplemental.Sets))
	for l := range rules.Supplemental.Sets {
		langs = append(langs, l)
	}
	slices.Sort(langs)

	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by go generate (internal/cldr/internal/gen) from CLDR %s. DO NOT EDIT.\n\npackage cldr\n\n", version)
	fmt.Fprintf(&b, "// Version is the release of the Unicode CLDR the tables come from.\nconst Version = %q\n\n", version)
	b.WriteString("// localeNames are the locales with data, sorted, separated by spaces.\n")
	fmt.Fprintf(&b, "const localeNames = %q\n\n", strings.Join(locales, " "))
	b.WriteString("// localeParents is the index of each locale's parent, -1 for und.\n")
	fmt.Fprintf(&b, "var localeParents = [...]int16{%s}\n\n", joinInts(parentIndex))
	b.WriteString("// packedLocales is each locale's entries, in which it differs from its\n// parent, deflated: records in localeNames' order separated by \\x1d,\n// entries by \\x1e, a key from its value by \\x1f.\n")
	fmt.Fprintf(&b, "const packedLocales = %q\n\n", packed.String())
	b.WriteString("// periodRules are the day periods of each language, by CLDR's rules:\n// \"name hh:mm hh:mm\" from and before, or \"name hh:mm\" at, by lines.\n")
	b.WriteString("var periodRules = map[string]string{\n")
	for _, l := range langs {
		set := rules.Supplemental.Sets[l]
		names := make([]string, 0, len(set))
		for n := range set {
			names = append(names, n)
		}
		slices.Sort(names)
		var lines []string
		for _, n := range names {
			r := set[n]
			if r.At != "" {
				lines = append(lines, n+" "+r.At)
			} else {
				lines = append(lines, n+" "+r.From+" "+r.Before)
			}
		}
		fmt.Fprintf(&b, "\t%q: %q,\n", l, strings.Join(lines, "\n"))
	}
	b.WriteString("}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(*out, "tables.go"), src, 0o644); err != nil {
		log.Fatal(err)
	}
}

func joinInts(v []int) string {
	s := make([]string, len(v))
	for i, n := range v {
		s[i] = fmt.Sprint(n)
	}
	return strings.Join(s, ", ")
}

// entries are a locale's own data, by key: months "M<context><width>.<n>",
// weekdays "E<context><width>.<n>" from Sunday, day periods
// "a<width>.<name>", eras "G<width>.<n>", the date, time, date-time and
// at-time patterns "D.<style>", "T.<style>", "DT.<style>", "AT.<style>",
// the skeletons' patterns "S.<skeleton>", the GMT formats "Zg", "Zz" and
// "Zh", and "N", the digits of its numbering system. A width is 3
// (abbreviated), 4 (wide), 5 (narrow) or 6 (short); a context f
// (format) or s (stand-alone).
func entries(files map[string][]byte, loc string, systems map[string]struct {
	Digits string `json:"_digits"`
}) map[string]string {
	out := map[string]string{}
	widths := map[string]string{"abbreviated": "3", "wide": "4", "narrow": "5", "short": "6"}
	contexts := map[string]string{"format": "f", "stand-alone": "s"}
	var greg map[string]map[string]struct {
		Dates struct {
			Calendars struct {
				Gregorian struct {
					Months          map[string]map[string]map[string]string `json:"months"`
					Days            map[string]map[string]map[string]string `json:"days"`
					DayPeriods      map[string]map[string]map[string]string `json:"dayPeriods"`
					Eras            map[string]map[string]string            `json:"eras"`
					DateFormats     map[string]string                       `json:"dateFormats"`
					TimeFormats     map[string]string                       `json:"timeFormats"`
					DateTimeFormats map[string]json.RawMessage              `json:"dateTimeFormats"`
				} `json:"gregorian"`
			} `json:"calendars"`
		} `json:"dates"`
	}
	path := "cldr-dates-full/main/" + loc + "/ca-gregorian.json"
	if _, ok := files[path]; !ok {
		return out
	}
	decode(files, path, &greg)
	g := greg["main"][loc].Dates.Calendars.Gregorian
	for ctx, byWidth := range g.Months {
		for w, names := range byWidth {
			if widths[w] == "" || widths[w] == "6" {
				continue
			}
			for n, v := range names {
				out["M"+contexts[ctx]+widths[w]+"."+n] = v
			}
		}
	}
	days := map[string]string{"sun": "0", "mon": "1", "tue": "2", "wed": "3", "thu": "4", "fri": "5", "sat": "6"}
	for ctx, byWidth := range g.Days {
		for w, names := range byWidth {
			for n, v := range names {
				out["E"+contexts[ctx]+widths[w]+"."+days[n]] = v
			}
		}
	}
	for w, names := range g.DayPeriods["format"] {
		if widths[w] == "" {
			continue
		}
		for n, v := range names {
			if !strings.Contains(n, "-alt-") {
				out["a"+widths[w]+"."+n] = v
			}
		}
	}
	eras := map[string]string{"eraAbbr": "3", "eraNames": "4", "eraNarrow": "5"}
	for w, names := range g.Eras {
		for n, v := range names {
			if n == "0" || n == "1" {
				out["G"+eras[w]+"."+n] = v
			}
		}
	}
	for _, style := range []string{"full", "long", "medium", "short"} {
		out["D."+style] = g.DateFormats[style]
		out["T."+style] = g.TimeFormats[style]
		var glue string
		json.Unmarshal(g.DateTimeFormats[style], &glue)
		out["DT."+style] = glue
	}
	if raw, ok := g.DateTimeFormats["availableFormats"]; ok {
		var skel map[string]string
		json.Unmarshal(raw, &skel)
		for k, v := range skel {
			if !strings.Contains(k, "-alt-") && !strings.Contains(k, "-count-") {
				out["S."+k] = v
			}
		}
	}
	var atTime map[string]map[string]struct {
		Dates struct {
			Calendars struct {
				Gregorian struct {
					AtTime map[string]map[string]string `json:"dateTimeFormats-atTime"`
				} `json:"gregorian"`
			} `json:"calendars"`
		} `json:"dates"`
	}
	decode(files, path, &atTime)
	for style, v := range atTime["main"][loc].Dates.Calendars.Gregorian.AtTime["standard"] {
		out["AT."+style] = v
	}

	var zones map[string]map[string]struct {
		Dates struct {
			TimeZoneNames struct {
				GMT     string `json:"gmtFormat"`
				GMTZero string `json:"gmtZeroFormat"`
				Hour    string `json:"hourFormat"`
			} `json:"timeZoneNames"`
		} `json:"dates"`
	}
	if zp := "cldr-dates-full/main/" + loc + "/timeZoneNames.json"; files[zp] != nil {
		decode(files, zp, &zones)
		z := zones["main"][loc].Dates.TimeZoneNames
		out["Zg"], out["Zz"], out["Zh"] = z.GMT, z.GMTZero, z.Hour
	}
	var nums map[string]map[string]struct {
		Numbers struct {
			Default string `json:"defaultNumberingSystem"`
		} `json:"numbers"`
	}
	if np := "cldr-numbers-full/main/" + loc + "/numbers.json"; files[np] != nil {
		decode(files, np, &nums)
		if s := nums["main"][loc].Numbers.Default; s != "" {
			out["N"] = systems[s].Digits
		}
	}
	for k, v := range out {
		if v == "" {
			delete(out, k)
		}
	}
	return out
}

func decode(files map[string][]byte, name string, v any) {
	data, ok := files[name]
	if !ok {
		log.Fatalf("%s is not in the packages", name)
	}
	if err := json.Unmarshal(data, v); err != nil {
		log.Fatalf("%s: %v", name, err)
	}
}

// read reads the JSON files of package name, checked against sum, into
// files by "<name>/<path in the package>".
func read(name, sum, cache string, files map[string][]byte) error {
	file := name + "-" + version + ".tgz"
	var data []byte
	var err error
	if cache != "" {
		data, err = os.ReadFile(filepath.Join(cache, file))
	} else {
		var resp *http.Response
		resp, err = http.Get("https://registry.npmjs.org/" + name + "/-/" + file)
		if err == nil {
			defer resp.Body.Close()
			if resp.StatusCode != http.StatusOK {
				return fmt.Errorf("%s: %s", file, resp.Status)
			}
			data, err = io.ReadAll(resp.Body)
		}
	}
	if err != nil {
		return err
	}
	if got := sha256.Sum256(data); hex.EncodeToString(got[:]) != sum {
		return fmt.Errorf("%s: SHA-256 %x, want %s", file, got, sum)
	}
	gz, err := gzip.NewReader(bytes.NewReader(data))
	if err != nil {
		return err
	}
	tr := tar.NewReader(gz)
	for {
		h, err := tr.Next()
		if err == io.EOF {
			return nil
		}
		if err != nil {
			return err
		}
		p, ok := strings.CutPrefix(h.Name, "package/")
		if !ok || !strings.HasSuffix(p, ".json") {
			continue
		}
		if strings.HasPrefix(p, "main/") && !strings.HasSuffix(p, "/ca-gregorian.json") &&
			!strings.HasSuffix(p, "/timeZoneNames.json") && !strings.HasSuffix(p, "/numbers.json") {
			continue
		}
		b, err := io.ReadAll(tr)
		if err != nil {
			return err
		}
		files[name+"/"+p] = b
	}
}
